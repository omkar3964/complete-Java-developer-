package basics;

public class DataTypes {
    public static void main(String[] args) {
        int a = 34;
        float b = 34.6f;
        double c = 34.2;
        boolean d = true;
        char e = 'E';
        short f = 323;
        long g = 25432345;
        byte h = 23;

//        binary nymber
        int i  = 0b1010;
        System.out.println(i);

//        hexadecimal
        int j = 0xA;
        System.out.println(j);

        long x = 10_000_00_00;
        System.out.println(x);
    }
}
